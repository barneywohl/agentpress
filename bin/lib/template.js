'use strict';

/**
 * Render an agents.txt file body given user choices + detected facts.
 * Sensible defaults for v1.0; intentionally conservative on permissions.
 */
function buildAgentsTxt({
  project,
  maintainer,
  contactForAgents,
  aiDisclosureRequired,
  allowPrsWithoutApproval,
  protectSensitivePaths,
  repoType,
}) {
  const today = new Date().toISOString().slice(0, 10);

  const baseAllowed = [
    'read_documentation',
    'read_source_code',
    'run_tests_in_ci',
    'comment_on_issue',
    'propose_design',
  ];
  if (allowPrsWithoutApproval) baseAllowed.splice(2, 0, 'file_pull_request');

  const baseProhibited = [
    'merge_to_main',
    'deploy_to_production',
    'modify_secrets',
    'exfiltrate_secrets',
    'bypass_2fa',
    'bypass_captcha',
    'deceptive_tracking',
    'spam',
    'impersonation',
  ];

  // Repo-type specific extra prohibited entries
  if (repoType.startsWith('node')) baseProhibited.push('publish_to_npm');
  if (repoType.startsWith('python')) baseProhibited.push('publish_to_pypi');

  const approvals = ['schema_migrations', 'production_deploys', 'dependency_upgrades_major', 'new_external_service_integrations'];
  const sensitiveGlobs = protectSensitivePaths
    ? 'payments/**, billing/**, auth/**, security/**, secrets/**'
    : null;

  const entryPoints = [
    'agent_guide = /AGENTS.md',
  ];
  if (repoType.startsWith('node')) entryPoints.push('test_command = npm test', 'lint_command = npm run lint');
  else if (repoType.startsWith('python')) entryPoints.push('test_command = python3 -m pytest -q');
  else if (repoType.startsWith('go')) entryPoints.push('test_command = go test ./...');
  else if (repoType.startsWith('rust')) entryPoints.push('test_command = cargo test');

  const lines = [];
  lines.push('# agents.txt v1.0');
  lines.push('# https://github.com/barneywohl/agentpress');
  lines.push('#');
  lines.push('# This file declares what autonomous AI agents are allowed and expected to do');
  lines.push('# in this repository. Generated by AgentPress; tailor as needed.');
  lines.push('');
  lines.push('[meta]');
  lines.push('spec_version = 1.0');
  lines.push(`project = ${project}`);
  lines.push(`maintainer = ${maintainer || 'maintainer@example.com'}`);
  if (contactForAgents) lines.push(`contact_for_agents = ${contactForAgents}`);
  lines.push(`last_updated = ${today}`);
  lines.push(`ai_disclosure_required = ${aiDisclosureRequired ? 'true' : 'false'}`);
  lines.push('');
  lines.push('[allowed_actions]');
  for (const a of baseAllowed) lines.push(a);
  lines.push('');
  lines.push('[prohibited_actions]');
  for (const a of baseProhibited) lines.push(a);
  lines.push('');
  lines.push('[requires_human_approval]');
  for (const a of approvals) lines.push(a);
  if (sensitiveGlobs) lines.push(`changes_touching = ${sensitiveGlobs}`);
  lines.push('');
  lines.push('[entry_points]');
  for (const ep of entryPoints) lines.push(ep);
  lines.push('');
  lines.push('[rate_limits]');
  lines.push('max_pull_requests_per_day = 5');
  lines.push('max_issues_per_day = 10');
  lines.push('max_comments_per_day = 25');
  lines.push('');
  lines.push('[scope]');
  lines.push('max_files_changed = 25');
  lines.push('max_lines_changed = 800');
  lines.push('single_purpose_pr = true');
  lines.push('');
  lines.push('[disclosure]');
  lines.push('pr_label = agent-authored');
  lines.push('commit_trailer = Authored-by-Agent: <agent-name> <agent-version>');
  lines.push(`require_attribution_in_pr_body = ${aiDisclosureRequired ? 'true' : 'false'}`);
  lines.push('');
  return lines.join('\n') + '\n';
}

function buildGithubWorkflow() {
  return `name: agents.txt validate

on:
  pull_request:
    paths: ['agents.txt']
  push:
    branches: [main]
    paths: ['agents.txt']

jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: barneywohl/agentpress/actions/setup-action@v1
        with:
          file: agents.txt
          fail-on-warnings: false
`;
}

function buildBadgeSnippet(origin) {
  // origin is { owner, repo } or null/undefined; the badge target is the spec
  // home, so the origin is only informational and doesn't affect the URL.
  return `[![agents.txt](https://img.shields.io/badge/agents.txt-v1.0-2563eb?style=flat-square&logo=githubactions&logoColor=white)](https://github.com/barneywohl/agentpress)`;
}

module.exports = { buildAgentsTxt, buildGithubWorkflow, buildBadgeSnippet };
